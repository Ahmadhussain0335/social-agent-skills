import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import {
  buildFfmpegArgs,
  probeWithFfmpeg,
  resolveShotList,
  runFfmpeg,
  type ShotList,
} from '../src/platforms/youtube/assemble';
import { resolveFfmpeg } from '../src/shared/ffmpeg';
import { pngHeader, tmp, write } from './helpers';

const probe = (durations: Record<string, number>) => (file: string) =>
  durations[Object.keys(durations).find((k) => file.endsWith(k)) ?? ''];

function mustPlan(list: ShotList, dir: string, p: Parameters<typeof resolveShotList>[2]) {
  const { plan, errors } = resolveShotList(list, dir, p);
  if (!plan) throw new Error(errors.join('; '));
  return plan;
}

function project(files: string[]) {
  const dir = tmp();
  for (const f of files) write(join(dir, f), 'x');
  return dir;
}

describe('resolveShotList', () => {
  it('resolves durations, probing clips without one', () => {
    const dir = project(['a.png', 'b.mp4', 'voice.mp3']);
    const list: ShotList = { voiceover: 'voice.mp3', segments: [{ file: 'a.png', duration: 3 }, { file: 'b.mp4' }] };
    const { plan, errors } = resolveShotList(list, dir, probe({ 'b.mp4': 4.5, 'voice.mp3': 7 }));
    expect(errors).toEqual([]);
    expect(plan).toMatchObject({ width: 1920, height: 1080, fps: 30, totalSeconds: 7.5, voiceoverSeconds: 7 });
  });

  it('reports every problem at once', () => {
    const dir = project(['a.png', 'c.txt', 'voice.mp3']);
    const list: ShotList = {
      resolution: '1919x1080',
      voiceover: 'voice.mp3',
      music: { file: 'missing.mp3', volume: 2 },
      segments: [{ file: 'a.png' }, { file: 'c.txt', duration: 1 }, { file: 'gone.mp4' }],
    };
    const { plan, errors } = resolveShotList(list, dir, probe({ 'voice.mp3': 30 }));
    expect(plan).toBeUndefined();
    expect(errors).toEqual([
      'resolution must be WIDTHxHEIGHT with even numbers, e.g. 1920x1080',
      'segments[0] (a.png): images need a positive duration in seconds',
      'segments[1] (c.txt): unsupported file type .txt',
      'segments[2] (gone.mp4): file not found',
      'music.file: file not found (missing.mp3)',
      'music.volume must be between 0 and 1',
      'visuals total 0s but the voiceover is 30s; extend segment durations so the voiceover is not cut off',
    ]);
  });
});

describe('buildFfmpegArgs', () => {
  it('builds a filter graph with voiceover, music and soft subtitles, without a shell', () => {
    const dir = project(['a.png', 'b.mp4', 'v.mp3', 'm.mp3', 's.srt']);
    const list: ShotList = {
      voiceover: 'v.mp3',
      music: { file: 'm.mp3', volume: 0.2 },
      subtitles: 's.srt',
      segments: [
        { file: 'a.png', duration: 2 },
        { file: 'b.mp4', duration: 3 },
      ],
    };
    const args = buildFfmpegArgs(list, mustPlan(list, dir, probe({ 'v.mp3': 4 })), false);
    expect(args.slice(0, 2)).toEqual(['-hide_banner', '-n']);
    expect(args).toContain('-filter_complex');
    const graph = args[args.indexOf('-filter_complex') + 1] as string;
    expect(graph).toContain('[v0][v1]concat=n=2:v=1:a=0[vout]');
    expect(graph).toContain('[2:a]apad[vo];[3:a]volume=0.2[mu]');
    expect(args).toEqual(expect.arrayContaining(['-map', '4:s', '-c:s', 'mov_text', '-t', '5']));
    expect(args.at(-1)).toBe('output/video.mp4');
  });

  it('adds a silent track when there is no audio', () => {
    const dir = project(['a.png']);
    const list: ShotList = { segments: [{ file: 'a.png', duration: 1 }] };
    const args = buildFfmpegArgs(
      list,
      mustPlan(list, dir, () => undefined),
      true,
    );
    expect(args).toEqual(expect.arrayContaining(['-y', '-f', 'lavfi', '-i', 'anullsrc=r=48000:cl=stereo']));
  });
});

const ffmpeg = resolveFfmpeg();
const ffmpegPath = ffmpeg?.path ?? '';

describe.skipIf(!ffmpeg)('ffmpeg integration', () => {
  it('renders a one-second clip from an image', async () => {
    const dir = tmp();
    const { spawnSync } = await import('node:child_process');
    // Real 64x36 PNG generated by ffmpeg itself so the test has no binary fixtures.
    spawnSync(ffmpegPath, [
      '-hide_banner',
      '-f',
      'lavfi',
      '-i',
      'color=c=blue:s=64x36',
      '-frames:v',
      '1',
      join(dir, 'a.png'),
    ]);
    expect(existsSync(join(dir, 'a.png'))).toBe(true);

    const list: ShotList = { resolution: '320x180', fps: 10, segments: [{ file: 'a.png', duration: 1 }] };
    const plan = mustPlan(list, dir, probeWithFfmpeg(ffmpegPath));
    await runFfmpeg(ffmpegPath, buildFfmpegArgs(list, plan, false), dir, plan.output);
    const length = probeWithFfmpeg(ffmpegPath)(join(dir, 'output/video.mp4'));
    expect(length).toBeGreaterThan(0.9);
    expect(length).toBeLessThan(1.2);
  });
});

it('png helper produces a valid header', () => {
  expect(pngHeader(2, 2).readUInt32BE(16)).toBe(2);
});
