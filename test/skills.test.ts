import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { bundledSkills } from '../src/core/catalog';
import { validateSkillDir } from '../src/core/skill-validator';
import { syncTargets } from '../tools/sync-refs.mjs';

const root = join(import.meta.dirname, '..');
const skillsRoot = join(root, 'skills');
const skillDirs = readdirSync(skillsRoot, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name);

describe('bundled skills', () => {
  it.each(skillDirs)('%s passes the spec and authoring rules', (name) => {
    expect(validateSkillDir(join(skillsRoot, name))).toEqual([]);
  });

  it('every skill except social-core requires social-core', () => {
    for (const skill of bundledSkills(skillsRoot)) {
      if (skill.name !== 'social-core') expect(skill.requires).toContain('social-core');
    }
  });

  it('shared reference docs are in sync with their source', () => {
    for (const { source, target } of syncTargets()) {
      expect(readFileSync(target, 'utf8'), `${target} is stale; run npm run build`).toBe(readFileSync(source, 'utf8'));
    }
  });

  it('bundled scripts exist and carry the generated-file banner', () => {
    const scripts = skillDirs.flatMap((name) => {
      const dir = join(skillsRoot, name, 'scripts');
      return existsSync(dir) ? readdirSync(dir).map((f) => join(dir, f)) : [];
    });
    expect(scripts.length).toBeGreaterThanOrEqual(6);
    for (const script of scripts) {
      expect(script.endsWith('.mjs')).toBe(true);
      expect(readFileSync(script, 'utf8').startsWith('// Generated by tsup')).toBe(true);
    }
  });
});
